export const dataset: Example[] = OUTCOMES.flatMap((expected) =>
  examples[expected].map((text, index) => ({
    id: `${expected}_${String(index + 1).padStart(3, "0")}`,
    text,
    expected,
  })),
);

export function validateDataset(input: unknown): Example[] {
  if (Array.isArray(input) && input.some((row) => row?.expected === "insight"))
    throw new Error("Insight is outside knowledge.classification:v1.");
  const rows = z.array(exampleSchema).min(1).max(500).parse(input);
  const ids = new Set<string>();
  const texts = new Set<string>();
  for (const row of rows) {
    const normalized = row.text.toLowerCase().replace(/[^a-z0-9]/g, "");
    if (ids.has(row.id) || texts.has(normalized))
      throw new Error("Duplicate dataset ID or candidate");
    if (
      !privacyEligible({
        id: row.id,
        kind: row.expected,
        statement: row.text,
        source: "synthetic",
      })
    )
      throw new Error("Dataset candidate failed privacy validation");
    ids.add(row.id);
    texts.add(normalized);
  }
  return rows;
}
export function datasetHash(rows: readonly Example[]): string {
  return createHash("sha256").update(JSON.stringify(rows)).digest("hex");
}
